export function translate(text: string, lang: Language): string {
  if (lang === 'ru') return text;
  const trimmed = text.trim();
  if (english[trimmed]) return text.replace(trimmed, english[trimmed]);
  // Dynamic display messages; identifiers, option values and media titles stay intact.
  return text
    .replace(/^Выбрано: (.*)\. Это пример\. Вставьте свою ссылку выше, чтобы скачать настоящее видео\.$/, 'Selected: $1. This is a sample. Paste your own link above to download a video.')
    .replace(/^Для этого ролика нет доступных вариантов видео со звуком\.$/, 'No video-with-audio options are available for this video.')
    .replace(/^Для этого ролика нет доступных вариантов аудио\.$/, 'No audio options are available for this video.')
    .replace(/Загружено примерно (\d+) процентов/, 'Approximately $1 percent downloaded')
    .replace(/Дорожка (\d+) из (\d+)\./, 'Track $1 of $2.')
    .replace(/Исходное качество/g, 'Original quality')
    .replace(/исходное качество/g, 'original quality')
    .replace(/максимум/g, 'up to').replace(/Размер файла:/g, 'File size:')
    .replace(/Со звуком/g, 'With sound').replace(/конвертация/g, 'conversion')
    .replace(/Проверка:/g, 'Checking:').replace(/Загрузка:/g, 'Downloading:').replace(/Обработка:/g, 'Processing:')
    .replace(/МБ\/с/g, 'MB/s').replace(/КБ\/с/g, 'KB/s').replace(/МБ/g, 'MB')
    .replace(/сек\./g, 'sec').replace(/мин\./g, 'min');
}
